# (Visualisation & Stats)

def analyser_graphe(graphe, nom_source):
    """Affiche des stats textuelles sur le graphe récupéré."""
    nb_triplets = len(graphe)
    nb_labels = 0
    nb_synonymes = 0

    for s, p, o in graphe:
        if p == RDFS.label: nb_labels += 1
        if p == SKOS.altLabel: nb_synonymes += 1

    print(f" ANALYSE {nom_source.upper()} :")
    print(f"   - Triplets totaux : {nb_triplets}")
    print(f"   - Labels principaux : {nb_labels}")
    print(f"   - Synonymes (altLabel) : {nb_synonymes}")
    print("-" * 40)

def visualiser_graphe(graph_rdf, titre="Graphe"):
    """Dessine le graphe RDF avec NetworkX."""
    if len(graph_rdf) == 0:
        print(f"Le graphe {titre} est vide, rien à afficher.")
        return

    nx_graph = nx.DiGraph()

    for s, p, o in graph_rdf:
        # On raccourcit les labels pour que le dessin soit lisible
        s_lbl = str(s).split("/")[-1].replace("CHEBI_", "CHEBI:")
        o_lbl = str(o).split("/")[-1]
        if isinstance(o, Literal):
            o_lbl = str(o)[:15] + "..." if len(str(o)) > 15 else str(o) # Tronquer les textes longs

        p_lbl = str(p).split("#")[-1] if "#" in str(p) else str(p).split("/")[-1]

        nx_graph.add_edge(s_lbl, o_lbl, label=p_lbl)

    plt.figure(figsize=(10, 6))
    pos = nx.spring_layout(nx_graph, k=0.6, iterations=50)

    # Dessin
    nx.draw(nx_graph, pos, with_labels=True,
            node_color='#A0CBE2', node_size=2500,
            font_size=9, font_weight="bold", arrows=True, connectionstyle='arc3, rad = 0.1')

    edge_labels = nx.get_edge_attributes(nx_graph, 'label')
    nx.draw_networkx_edge_labels(nx_graph, pos, edge_labels=edge_labels, font_size=8)

    plt.title(titre)
    plt.axis('off')
    plt.show()

