import sys

print("\n🔍 ÉTAPE 1 : RÉCUPÉRATION WIKIDATA...")
g_wd = Graph()

# 1. On définit l'agent (OBLIGATOIRE pour ne pas être bloqué)
user_agent = "Projet_PFE_Servier_ECE/1.0 (contact@ece.fr) python-sparqlwrapper"
sparql = SPARQLWrapper("https://query.wikidata.org/sparql", agent=user_agent)

ids_wd = " ".join([f"wd:{m['wd']}" for m in molecules])

query = f"""
SELECT ?entity ?label ?altLabel WHERE {{
  VALUES ?entity {{ {ids_wd} }}

  # On récupère le label principal
  ?entity rdfs:label ?label .
  FILTER(LANG(?label) = "fr")

  # On récupère les synonymes (Optionnel)
  OPTIONAL {{
    ?entity skos:altLabel ?altLabel .
    FILTER(LANG(?altLabel) = "fr")
  }}
}}
"""

sparql.setQuery(query)
sparql.setReturnFormat(JSON)
# On augmente le temps d'attente autorisé avant erreur (timeout)
sparql.setTimeout(60)

try:
    results = sparql.query().convert()

    # Vérification : A-t-on reçu des résultats ?
    bindings = results["results"]["bindings"]
    print(f"   -> {len(bindings)} lignes de données reçues.")

    if len(bindings) == 0:
        print("⚠️ ATTENTION : Wikidata a répondu 0 résultat. Vérifiez les IDs.")

    for res in bindings:
        uri = URIRef(res["entity"]["value"])
        if "label" in res:
            g_wd.add((uri, RDFS.label, Literal(res["label"]["value"], lang="fr")))
        if "altLabel" in res:
            g_wd.add((uri, SKOS.altLabel, Literal(res["altLabel"]["value"], lang="fr")))

    # Sauvegarde
    g_wd.serialize("source_wikidata.ttl", format="turtle")
    print("✅ Fichier 'source_wikidata.ttl' généré avec succès.")

except Exception as e:
    print(f"❌ ERREUR CRITIQUE WIKIDATA : {e}")
