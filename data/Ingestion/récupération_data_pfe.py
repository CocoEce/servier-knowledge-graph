print("\n🧪 ÉTAPE 2 : GÉNÉRATION PUBCHEM (Technique)...")
g_pc = Graph()

for mol in molecules:
    uri = PC[f"CID{mol['pubchem']}"]
    g_pc.add((uri, RDF.type, URIRef("http://semanticscience.org/resource/ChemicalCompound")))
    g_pc.add((uri, RDFS.label, Literal(f"Compound CID {mol['pubchem']}"))) # Nom technique
    g_pc.add((uri, URIRef("http://example.org/id"), Literal(mol['pubchem'])))

